CREATE TABLE ROOM (
    ID       BIGINT       NOT NULL PRIMARY KEY,
    NAME     VARCHAR(100) NOT NULL,
    FLOOR    INT          NOT NULL,
    CAPACITY INT          NOT NULL,
    CONSTRAINT CK_ROOM_CAPACITY CHECK (CAPACITY >= 1)
);

CREATE TABLE RESERVATION (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ROOM_ID          BIGINT      NOT NULL,
    RESERVATION_DATE DATE        NOT NULL,
    START_TIME       TIME        NOT NULL,
    END_TIME         TIME        NOT NULL,
    TITLE            VARCHAR(50) NOT NULL,
    ATTENDEE_COUNT   INT         NOT NULL,
    RESERVED_BY      VARCHAR(64) NOT NULL,
    STATUS           VARCHAR(16) NOT NULL,
    CANCELLED_AT     TIMESTAMP,
    CREATED_AT       TIMESTAMP   NOT NULL,
    CONSTRAINT FK_RESERVATION_ROOM FOREIGN KEY (ROOM_ID) REFERENCES ROOM (ID) ON DELETE RESTRICT,
    CONSTRAINT CK_RESERVATION_STATUS CHECK (STATUS IN ('RESERVED', 'CANCELLED')),
    CONSTRAINT CK_RESERVATION_TIME CHECK (START_TIME < END_TIME)
);

CREATE INDEX IX_RESERVATION_ROOM_DATE ON RESERVATION (ROOM_ID, RESERVATION_DATE, START_TIME);
